-- Name: fn_materializar_pacientes_contatos_base(text, integer); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.fn_materializar_pacientes_contatos_base(p_coluna_chave text, p_limit integer DEFAULT 50) RETURNS bigint
    LANGUAGE plpgsql
    AS $$
declare
  v_status text;
  v_inserted bigint;
begin
  if p_coluna_chave = 'recuperacao_base' then
    v_status := 'recuperacao_base';
  elsif p_coluna_chave = 'a_contactar' then
    v_status := 'a_contactar';
  else
    raise exception 'Coluna base inválida: %', p_coluna_chave;
  end if;

  with candidatos as (
    select p.id
    from public.pacientes p
    where p.ativo = true
      and p.recuperacao_base = (p_coluna_chave = 'recuperacao_base')
      and not exists (
        select 1
        from public.contatos_base cb
        where cb.paciente_id = p.id
      )
    order by p.nome asc, p.id asc
    limit greatest(coalesce(p_limit, 50), 0)
  ), inseridos as (
    insert into public.contatos_base (
      paciente_id,
      status,
      kanban_coluna_chave
    )
    select
      candidatos.id,
      v_status,
      p_coluna_chave
    from candidatos
    on conflict (paciente_id) do nothing
    returning 1
  )
  select count(*)::bigint into v_inserted from inseridos;

  return coalesce(v_inserted, 0);
end;
$$;


