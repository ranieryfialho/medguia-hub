--
-- Name: vw_paciente_uso; Type: VIEW; Schema: public; Owner: -
--

CREATE VIEW public.vw_paciente_uso AS
 SELECT p.id,
    p.nome,
    p.cpf,
    p.telefone,
    p.telefone_secundario,
    p.email,
    p.data_nascimento,
    p.ativo,
    COALESCE(a.cnt, (0)::bigint) AS atendimentos,
    COALESCE(ag.cnt, (0)::bigint) AS agendamentos,
    COALESCE(pr.cnt, (0)::bigint) AS prontuarios,
    COALESCE(ev.cnt, (0)::bigint) AS eventos_paciente,
    COALESCE(cb.cnt, (0)::bigint) AS contatos_base,
    COALESCE(nc.cnt, (0)::bigint) AS notas_contato,
    COALESCE(vd.cnt, (0)::bigint) AS vendas,
    ((((((COALESCE(a.cnt, (0)::bigint) + COALESCE(ag.cnt, (0)::bigint)) + COALESCE(pr.cnt, (0)::bigint)) + COALESCE(ev.cnt, (0)::bigint)) + COALESCE(cb.cnt, (0)::bigint)) + COALESCE(nc.cnt, (0)::bigint)) + COALESCE(vd.cnt, (0)::bigint)) AS total_relacionamentos
   FROM (((((((public.pacientes p
     LEFT JOIN ( SELECT atendimentos.paciente_id,
            count(*) AS cnt
           FROM public.atendimentos
          GROUP BY atendimentos.paciente_id) a ON ((a.paciente_id = p.id)))
     LEFT JOIN ( SELECT agendamentos.paciente_id,
            count(*) AS cnt
           FROM public.agendamentos
          GROUP BY agendamentos.paciente_id) ag ON ((ag.paciente_id = p.id)))
     LEFT JOIN ( SELECT prontuarios.paciente_id,
            count(*) AS cnt
           FROM public.prontuarios
          GROUP BY prontuarios.paciente_id) pr ON ((pr.paciente_id = p.id)))
     LEFT JOIN ( SELECT eventos_paciente.paciente_id,
            count(*) AS cnt
           FROM public.eventos_paciente
          GROUP BY eventos_paciente.paciente_id) ev ON ((ev.paciente_id = p.id)))
     LEFT JOIN ( SELECT contatos_base.paciente_id,
            count(*) AS cnt
           FROM public.contatos_base
          GROUP BY contatos_base.paciente_id) cb ON ((cb.paciente_id = p.id)))
     LEFT JOIN ( SELECT notas_contato.paciente_id,
            count(*) AS cnt
           FROM public.notas_contato
          GROUP BY notas_contato.paciente_id) nc ON ((nc.paciente_id = p.id)))
     LEFT JOIN ( SELECT vendas.paciente_id,
            count(*) AS cnt
           FROM public.vendas
          GROUP BY vendas.paciente_id) vd ON ((vd.paciente_id = p.id)));


